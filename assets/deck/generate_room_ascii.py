"""Bake a filamentary ASCII nebula, with a faint infinity-shaped flow.

Python 3, standard library only. Both compositions are fixed colour character
fields: no browser renderer, embedded font, animation or external dependency.
Individual glyph coordinates avoid SVG whitespace/textLength bugs in WebKit.
"""
from collections import defaultdict
from math import cos, exp, floor, hypot, pi, sin
from pathlib import Path
import random

OUT = Path(__file__).resolve().parent
RAMP = " .,:;+=*#%@"
CELL_X, CELL_Y = 6, 9


def noise(x, y):
    ix, iy = floor(x), floor(y)
    tx, ty = x - ix, y - iy
    tx, ty = tx * tx * (3 - 2 * tx), ty * ty * (3 - 2 * ty)
    def hash_at(a, b):
        n = ((a * 374761393 + b * 668265263) ^ 0x5F3759DF) & 0xffffffff
        n = ((n ^ (n >> 13)) * 1274126177) & 0xffffffff
        return ((n ^ (n >> 16)) & 65535) / 65535
    a = hash_at(ix, iy) * (1 - tx) + hash_at(ix + 1, iy) * tx
    b = hash_at(ix, iy + 1) * (1 - tx) + hash_at(ix + 1, iy + 1) * tx
    return a * (1 - ty) + b * ty


def field(columns, rows, portrait=False):
    rng = random.Random(40621)
    aspect = columns * CELL_X / (rows * CELL_Y)
    half_y = 1.12 if not portrait else 1.88
    half_x = half_y * aspect
    angle = -.32 if not portrait else -pi / 2 + .17
    curve = []
    for n in range(640):
        t = n / 640 * 2 * pi
        den = 1 + .52 * sin(t) ** 2
        u = 1.39 * cos(t) / den + .11 * sin(3 * t)
        v = .60 * sin(2 * t) / den + .045 * sin(5 * t)
        curve.append((u * cos(angle) - v * sin(angle),
                      u * sin(angle) + v * cos(angle), t))
    result = []
    for row in range(rows):
        y = (row + .5) / rows * 2 * half_y - half_y
        for col in range(columns):
            x = (col + .5) / columns * 2 * half_x - half_x
            n1 = noise(x * 7 + 12, y * 7 - 9)
            n2 = noise(x * 23 - 8, y * 23 + 17)
            n3 = noise(x * 59 + 4, y * 59 - 8)
            n4 = noise(x * 131 - 2, y * 131 + 3)
            # Domain warping breaks up the ribbon into fine bent cloud wisps.
            wx = x + .035 * (n1 - .5) + .014 * (n3 - .5)
            wy = y + .045 * (n2 - .5) + .013 * (n4 - .5)
            cx, cy, phase = min(curve, key=lambda p: (p[0] - wx) ** 2 + (p[1] - wy) ** 2)
            d = hypot(cx - wx, cy - wy)
            # Long uneven arms; most of the mathematical loop remains dark.
            arc = .15 + .85 * (.5 + .5 * sin(2 * phase - .7)) ** 1.6
            width = .043 + .040 * n1
            cloud = (.26 + .95 * n2 + .35 * n3) ** 2
            spine = .75 * exp(-(d / width) ** 2) * cloud
            veil = .24 * exp(-(d / .19) ** 2) * (n1 * n2 * 2) ** 2
            ridges = .48 * exp(-((d - .086 - .018 * sin(11 * phase)) / .012) ** 2) * n2
            value = (spine + veil + ridges) * arc
            # Tiny, irregular bright knots replace continuous bands of type.
            value *= .48 + .65 * n4 + rng.random() * .33
            value *= min(1., max(0., (half_x - abs(x)) / .16), max(0., (half_y - abs(y)) / .13))
            value = min(1., value)
            if value > .075:
                intensity = min(8, max(0, int(value * 9)))
                glyph = RAMP[min(len(RAMP) - 1, max(1, int(value * (len(RAMP) - 1)) + 1))]
                # Cold dust, bright ice-blue ridges and rare warm filaments.
                warm = sin(phase * 2 + 1.8) > .62 and n1 > .51
                palette = ('#2b2044', '#4d295a', '#804070', '#b5598b', '#e77b9e', '#ffa5b8', '#ffd1c8', '#ffe6d6', '#fff4e1') if warm else (
                    '#102344', '#183f68', '#206799', '#228dbb', '#35bfd7', '#6bdfeb', '#9decf4', '#c7fff4', '#fff8e7')
                result.append((col, row, glyph, palette[intensity]))
            elif rng.random() > .9977:
                result.append((col, row, '.', '#49617c' if rng.random() < .9 else '#a9c6ce'))
    return result


def svg(points, columns, rows):
    width, height = columns * CELL_X, rows * CELL_Y
    groups = defaultdict(list)
    for col, row, glyph, colour in points:
        groups[(colour, glyph)].append((col * CELL_X, row * CELL_Y + 8))
    runs = []
    # Every glyph is explicitly positioned; there are no whitespace runs for
    # WebKit to collapse and no textLength stretching. Grouping keeps files small.
    for (colour, glyph), coordinates in sorted(groups.items()):
        xs = ' '.join(str(p[0]) for p in coordinates)
        ys = ' '.join(str(p[1]) for p in coordinates)
        runs.append(f'<text fill="{colour}" x="{xs}" y="{ys}">{glyph * len(coordinates)}</text>')
    body = '\n'.join(runs)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" preserveAspectRatio="xMidYMid meet">
<!-- Generated by generate_room_ascii.py: static individually positioned ASCII. -->
<g font-family="monospace" font-size="9" font-weight="400">
{body}
</g>
</svg>
'''


if __name__ == '__main__':
    for name, columns, rows, portrait in [('room-infinity-ascii.svg', 420, 174, False),
                                           ('room-infinity-ascii-mobile.svg', 190, 288, True)]:
        content = svg(field(columns, rows, portrait), columns, rows)
        (OUT / name).write_text(content)
        print(f'{name}: {len(content):,} bytes')
